"""Grounded, labelled field probe storage. Never fabricate tunnel packet loss.

Authenticated user submits reports generated by client/duc_socks_probe.py.
No passwords are included, and a report is not proof of server-side authenticity.
"""
from __future__ import annotations
import datetime, fcntl, ipaddress, json, math, os, pathlib, time
from . import core

FILE = core.STATE / 'telemetry-client.json'
LOCK = core.STATE / 'telemetry.lock'
MAX_HISTORY = 150


def validate(report):
    if type(report) is not dict or len(json.dumps(report))>16000:
        raise ValueError('Invalid or oversized report')
    if report.get('schema')!=1 or report.get('measurement') not in ('real-client-socks5-https','client-iodine-icmp'):
        raise ValueError('Unsupported field probe schema/type')
    engine=report.get('engine')
    if engine not in core.ENGINES:raise ValueError('Unknown engine')
    ts=report.get('timestamp')
    if type(ts) is not str or len(ts)>40:raise ValueError('Missing timestamp')
    try:
        dt=datetime.datetime.fromisoformat(ts.replace('Z','+00:00'))
        if dt.tzinfo is None:raise ValueError()
    except (ValueError,TypeError):raise ValueError('Invalid offset-aware timestamp')
    if not (time.time()-86400*31 <= dt.timestamp() <= time.time()+600):
        raise ValueError('Report timestamp is more than 31d old or in the future')
    samples=report.get('samples'); success=report.get('successful'); failed=report.get('failed')
    if any(type(v) is not int for v in (samples,success,failed)) or not 1<=samples<=100 or success<0 or failed<0 or success+failed!=samples:
        raise ValueError('Inconsistent sample counts')
    rate=report.get('request_failure_pct')
    if type(rate) not in (int,float) or not math.isfinite(rate) or abs(rate-(failed/samples*100))>0.011:
        raise ValueError('Incorrect request failure rate')
    numerical=('socks_connect_rtt_ms','http_ttfb_ms','http_throughput_bps')
    for k in numerical:
        value=report.get(k)
        if value is not None and (type(value) not in (int,float) or not math.isfinite(value) or not 0<=value<=1e11):
            raise ValueError('Invalid numeric measurement '+k)
    if report.get('raw_dns_packet_loss_pct') is not None:
        raise ValueError('SOCKS reports cannot claim raw DNS packet loss')
    ip=report.get('exit_ip')
    if ip is not None:
        if type(ip) is not str:raise ValueError('Invalid exit IP')
        try:ipaddress.ip_address(ip)
        except ValueError:raise ValueError('Invalid exit IP')
    clean={k:report.get(k) for k in ['schema','engine','timestamp','measurement','samples','successful',
            'failed','request_failure_pct','socks_connect_rtt_ms','http_ttfb_ms','http_throughput_bps','exit_ip']}
    clean['raw_dns_packet_loss_pct']=None
    # ICMP is an actual (IP-level) packet loss measurement for iodine, separate from DNS packet loss.
    if report['measurement']=='client-iodine-icmp':
        if engine!='iodine':raise ValueError('ICMP mode restricted to iodine')
        pct=report.get('icmp_packet_loss_pct')
        if type(pct) not in (int,float) or not math.isfinite(pct) or not 0<=pct<=100:
            raise ValueError('ICMP loss must be 0..100')
        clean['icmp_packet_loss_pct']=pct
    return clean


def all_reports():
    try:
        value=json.loads(FILE.read_text())
        return value if isinstance(value,list) else []
    except (OSError,ValueError):return []


def save(data):
    record=validate(data)
    core.STATE.mkdir(parents=True,exist_ok=True,mode=0o700)
    with LOCK.open('a+') as handle:
        fcntl.flock(handle.fileno(),fcntl.LOCK_EX)
        old=all_reports()
        if any(x.get('engine')==record['engine'] and x.get('timestamp')==record['timestamp'] for x in old):
            raise ValueError('Duplicate field report')
        old.append(record)
        core.atomic_json(FILE,old[-MAX_HISTORY:])
    return {'stored':True,'engine':record['engine'],'timestamp':record['timestamp'],
            'note':'Client-reported application metrics; not raw DNS packet loss or per-engine VPS interface counters'}


def snapshot():
    reports=all_reports()
    latest={}
    for r in reports:
        e=r.get('engine')
        if e in core.ENGINES and (e not in latest or r.get('timestamp','')>latest[e].get('timestamp','')):
            latest[e]=r
    return {'version':1,'latest':latest,'history':reports[-60:],
            'definitions':{
                'request_failure_pct':'Failed HTTPS over SOCKS attempts / all attempts (client-side). NOT DNS packet loss.',
                'socks_connect_rtt_ms':'Median time to establish TCP + SOCKS authentication + CONNECT, measured on client.',
                'http_throughput_bps':'HTTP body bytes per second (not DNS payload speed or raw link throughput).',
                'icmp_packet_loss_pct':'Actual IP-level ping loss, only for iodine with a routed IP tunnel.',
                'raw_dns_packet_loss_pct':'Unavailable without per-engine DNS packet instrumentation.',
                'vps_rx_tx':'Host-wide NIC counters from system metrics; not engine-specific.'}}


def main():
    import argparse
    p=argparse.ArgumentParser(description='Import/inspect real client tunnel reports')
    p.add_argument('action',choices=['status','import'])
    p.add_argument('file',nargs='?')
    a=p.parse_args()
    if a.action=='import':
        if not a.file or os.geteuid()!=0:p.error('import requires a JSON path and root')
        f=pathlib.Path(a.file)
        if not f.is_file() or f.stat().st_size>16000:p.error('Invalid report file')
        result=save(json.loads(f.read_text()))
    else:result=snapshot()
    print(json.dumps(result,ensure_ascii=False,indent=2))

if __name__=='__main__':main()
